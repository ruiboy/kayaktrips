// One-shot migration export. Reads the live Supabase project (public tables
// and the public bucket, so the anon key is enough) and writes two things:
//
//   db/seed.sql          — every row, with uploader UUIDs resolved to emails
//   db/photos/<key>      — every photo file, renamed to its new R2 key
//   db/upload-photos.sh  — the wrangler commands to push those files to R2
//
// All three are gitignored: seed.sql carries real email addresses and the repo
// is public.
//
// Nothing here writes to Cloudflare or to Supabase. Run it as often as needed.

import { mkdir, writeFile, rm } from 'node:fs/promises'
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outDir = join(root, 'db')
const photoDir = join(outDir, 'photos')

const SUPABASE_URL = process.env.SUPABASE_URL
const SUPABASE_KEY = process.env.SUPABASE_KEY
if (!SUPABASE_URL || !SUPABASE_KEY) {
  console.error('SUPABASE_URL and SUPABASE_KEY must be set (source .env first)')
  process.exit(1)
}

const users = JSON.parse(readFileSync(join(outDir, 'users.local.json'), 'utf8'))

// Attribution is best-effort: a UUID with no known email becomes NULL, which
// is exactly what `on delete set null` meant on the old FK.
const emailFor = (uuid) => (uuid && users[uuid]) || null

async function table(name, query = '') {
  const res = await fetch(`${SUPABASE_URL}/rest/v1/${name}?select=*${query}`, {
    headers: { apikey: SUPABASE_KEY },
  })
  if (!res.ok) throw new Error(`${name}: ${res.status} ${await res.text()}`)
  return res.json()
}

const q = (v) => {
  if (v === null || v === undefined) return 'null'
  if (typeof v === 'number') return String(v)
  return `'${String(v).replace(/'/g, "''")}'`
}

// Postgres hands back '2026-09-07T12:50:09.634596+00:00'; the text columns
// hold ISO 8601 in UTC with a Z, matching what nowIso() writes.
const iso = (v) => (v ? new Date(v).toISOString() : null)

const EXT_BY_TYPE = {
  'image/jpeg': 'jpg',
  'image/png': 'png',
  'image/webp': 'webp',
  'image/gif': 'gif',
  'image/avif': 'avif',
  'image/heic': 'heic',
}

const [trips, campsites, photos] = await Promise.all([
  table('trips'),
  table('campsites'),
  table('photos'),
])

console.log(`read ${trips.length} trips, ${campsites.length} campsites, ${photos.length} photos`)

await rm(photoDir, { recursive: true, force: true })
await mkdir(photoDir, { recursive: true })

// Storage keys become '<photo-id>.<ext>'. The extension comes from what the
// bucket actually served, not from the old filename.
const uploads = []
for (const photo of photos) {
  const url = `${SUPABASE_URL}/storage/v1/object/public/photos/${photo.storage_path}`
  const res = await fetch(url)
  if (!res.ok) {
    console.warn(`  ! ${photo.id}: ${res.status} fetching ${photo.storage_path} — skipped`)
    photo.__skip = true
    continue
  }
  const type = res.headers.get('content-type')?.split(';')[0] ?? ''
  const ext = EXT_BY_TYPE[type] ?? photo.storage_path.split('.').pop()
  const key = `${photo.id}.${ext}`
  await writeFile(join(photoDir, key), Buffer.from(await res.arrayBuffer()))
  photo.__key = key
  photo.__type = type || 'application/octet-stream'
  uploads.push(photo)
}
console.log(`downloaded ${uploads.length} photo files`)

const live = photos.filter((p) => !p.__skip)
const lines = []

lines.push('-- Generated by scripts/export-from-supabase.mjs. Do not edit by hand.')
lines.push('-- Contains real email addresses; gitignored deliberately.')
lines.push('')
lines.push('delete from campsites;')
lines.push('delete from photos;')
lines.push('delete from trips;')
lines.push('')

// trips and photos reference each other, so trips go in without their badge
// and get it back at the end.
lines.push('-- trips (badge_photo_id backfilled below)')
for (const t of trips) {
  lines.push(
    `insert into trips (id, slug, title, start_date, end_date, start_place, end_place, start_lat, start_lon, end_lat, end_lon, notes, badge_photo_id, created_by, created_at) values (${[
      t.id, t.slug, t.title, t.start_date, t.end_date, t.start_place, t.end_place,
      t.start_lat, t.start_lon, t.end_lat, t.end_lon, t.notes, null,
      emailFor(t.created_by), iso(t.created_at),
    ].map(q).join(', ')});`,
  )
}

lines.push('')
lines.push('-- photos')
for (const p of live) {
  lines.push(
    `insert into photos (id, storage_path, uploaded_by, caption, trip_id, created_at) values (${[
      p.id, p.__key, emailFor(p.uploaded_by), p.caption, p.trip_id, iso(p.created_at),
    ].map(q).join(', ')});`,
  )
}

lines.push('')
lines.push('-- campsites')
for (const c of campsites) {
  lines.push(
    `insert into campsites (id, trip_id, name, camped_on, notes, lat, lon, bankage, campspots, firewood, shelter, aesthetics, created_by, created_at) values (${[
      c.id, c.trip_id, c.name, c.camped_on, c.notes, c.lat, c.lon,
      c.bankage, c.campspots, c.firewood, c.shelter, c.aesthetics,
      emailFor(c.created_by), iso(c.created_at),
    ].map(q).join(', ')});`,
  )
}

const badged = trips.filter((t) => t.badge_photo_id && live.some((p) => p.id === t.badge_photo_id))
if (badged.length) {
  lines.push('')
  lines.push('-- badges, now that the photos exist')
  for (const t of badged) {
    lines.push(`update trips set badge_photo_id = ${q(t.badge_photo_id)} where id = ${q(t.id)};`)
  }
}

lines.push('')
await writeFile(join(outDir, 'seed.sql'), lines.join('\n'))
console.log(`wrote db/seed.sql (${lines.length} lines)`)

const sh = [
  '#!/bin/sh',
  '# Generated by scripts/export-from-supabase.mjs.',
  '# Pushes the downloaded photo files into R2 under their new keys.',
  'set -e',
  `cd "$(dirname "$0")/.."`,
  '',
  '# The local binary, not npx: thirty npx invocations spend longer resolving',
  '# the package than transferring the files.',
  'W=node_modules/.bin/wrangler',
  '',
  ...uploads.map(
    (p, i) =>
      `echo "[${i + 1}/${uploads.length}] ${p.__key}"\n` +
      `$W r2 object put "kayaktrips-photos/${p.__key}" --file="db/photos/${p.__key}" --content-type="${p.__type}" --remote`,
  ),
  '',
  `echo "uploaded ${uploads.length} objects"`,
]
await writeFile(join(outDir, 'upload-photos.sh'), sh.join('\n'), { mode: 0o755 })
console.log(`wrote db/upload-photos.sh (${uploads.length} objects)`)
